-- WhatsApp CRM (fase 2): cobranças (PIX de longa validade e boleto) enviadas pela conversa,
-- manuais ou geradas pelas assinaturas; régua de lembretes; confirmação pelo webhook único.

CREATE TABLE `whatsapp_charges` (
  `id` CHAR(36) NOT NULL DEFAULT (uuid()),
  `organization_id` CHAR(36) NOT NULL,
  `customer_id` CHAR(36) NOT NULL,
  `subscription_id` CHAR(36) NULL,
  `product_id` CHAR(36) NULL,
  `chat_id` VARCHAR(64) NOT NULL,
  `kind` VARCHAR(8) NOT NULL DEFAULT 'pix',
  `amount_cents` INT NOT NULL,
  `description` VARCHAR(255) NOT NULL,
  `due_at` DATE NOT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  `origin` VARCHAR(16) NOT NULL DEFAULT 'manual',
  `provider` VARCHAR(32) NULL,
  `pix_charge_id` VARCHAR(128) NULL,
  `pix_code` TEXT NULL,
  `pix_qr_media_id` CHAR(36) NULL,
  `pix_expires_at` DATETIME(3) NULL,
  `boleto_charge_id` VARCHAR(128) NULL,
  `boleto_url` VARCHAR(500) NULL,
  `boleto_barcode` VARCHAR(80) NULL,
  `boleto_digitable` VARCHAR(80) NULL,
  `boleto_expires_at` DATETIME(3) NULL,
  `paid_via` VARCHAR(16) NULL,
  `paid_at` DATETIME(3) NULL,
  `paid_manual_by` CHAR(36) NULL,
  `sent_at` DATETIME(3) NULL,
  `reminders` JSON NULL,
  `error` VARCHAR(255) NULL,
  `created_by` CHAR(36) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `idx_wachg_org_status_due` (`organization_id`, `status`, `due_at`),
  INDEX `idx_wachg_customer` (`customer_id`, `created_at`),
  INDEX `idx_wachg_sub_due` (`subscription_id`, `due_at`),
  INDEX `idx_wachg_pix` (`pix_charge_id`),
  INDEX `idx_wachg_boleto` (`boleto_charge_id`),
  CONSTRAINT `fk_wachg_org` FOREIGN KEY (`organization_id`) REFERENCES `organizations` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_wachg_customer` FOREIGN KEY (`customer_id`) REFERENCES `whatsapp_customers` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_wachg_sub` FOREIGN KEY (`subscription_id`) REFERENCES `whatsapp_subscriptions` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_wachg_product` FOREIGN KEY (`product_id`) REFERENCES `whatsapp_products` (`id`) ON DELETE SET NULL
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
