CREATE TABLE IF NOT EXISTS `whatsapp_media` (
  `id` CHAR(36) NOT NULL DEFAULT (uuid()),
  `organization_id` CHAR(36) NOT NULL,
  `kind` VARCHAR(16) NOT NULL,
  `mime` VARCHAR(128) NOT NULL,
  `filename` VARCHAR(255) NULL,
  `size_bytes` BIGINT NOT NULL DEFAULT 0,
  `storage_path` VARCHAR(512) NOT NULL,
  `sha1` CHAR(40) NULL,
  `expires_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `idx_wamedia_org` (`organization_id`, `created_at`),
  INDEX `idx_wamedia_expires` (`expires_at`),
  CONSTRAINT `fk_wamedia_org` FOREIGN KEY (`organization_id`) REFERENCES `organizations` (`id`) ON DELETE CASCADE ON UPDATE NO ACTION
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

